"""Relocate startup paths without rewriting the installed configuration."""

from __future__ import annotations

import re
from pathlib import Path

from .errors import GmatError

ASSIGNMENT = re.compile(r"^\s*([A-Za-z][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$")
TOKEN = re.compile(r"^([A-Z][A-Z0-9_]*)(?=[/\\]|$)")


def prepare_startup(
    source: Path, bin_dir: Path, workspace: Path, plugin_aliases: dict[str, str] | None = None
) -> tuple[Path, list[str]]:
    try:
        lines = source.read_text(encoding="utf-8-sig").splitlines()
    except OSError as exc:
        raise GmatError("STARTUP_ERROR", f"Cannot read startup file {source}: {exc}") from exc
    entries = []
    for index, line in enumerate(lines, 1):
        match = ASSIGNMENT.match(line) if not line.lstrip().startswith("#") else None
        if match:
            key, value = match.groups()
            # GMAT recognizes full comment lines, not inline '#' comments.
            value = value.strip()
            entries.append((key, value))
        elif line.strip() and not line.lstrip().startswith("#"):
            raise GmatError("STARTUP_ERROR", f"Invalid startup assignment at {source}:{index}")
    definitions = dict(entries)
    for child in ("output", "updates", "logs"):
        (workspace / child).mkdir(parents=True, exist_ok=True)
    overrides = {
        "OUTPUT_PATH": (workspace / "output").as_posix() + "/",
        "LOG_FILE": (workspace / "logs/engine.log").as_posix(),
        "FILE_UPDATE_PATH": (workspace / "updates").as_posix() + "/",
        "PERSONALIZATION_FILE": (workspace / "Gmat.ini").as_posix(),
        "WRITE_PERSONALIZATION_FILE": "OFF",
    }
    definitions.update(overrides)

    def resolve(value: str, seen: tuple[str, ...] = ()) -> str:
        match = TOKEN.match(value)
        if match and match[1] in definitions:
            key = match[1]
            if key in seen:
                raise GmatError("STARTUP_ERROR", f"Cyclic startup path reference: {key}")
            value = resolve(definitions[key], (*seen, key)).rstrip("/\\") + value[len(key) :]
        # A relative startup path is relative to GMAT's bin directory, not the copied file.
        path = Path(value.replace("\\", "/"))
        return (path if path.is_absolute() else bin_dir / path).resolve().as_posix()

    output = [f"# Generated by gmat-mcp from {source}; installation unchanged."]
    plugins: list[str] = []
    for key, value in entries:
        value = overrides.get(key, value)
        if key.endswith(("_PATH", "_FILE")) or key == "PLUGIN":
            value = resolve(value)
            if key.endswith("_PATH"):
                value += "/"
        if key == "PLUGIN":
            value = (plugin_aliases or {}).get(value, value)
            plugins.append(value)
        output.append(f"{key} = {value}")
    for key, value in overrides.items():
        if key not in dict(entries):
            output.append(f"{key} = {value}")
    destination = workspace / "startup.txt"
    destination.write_text("\n".join(output) + "\n", encoding="utf-8")
    return destination, plugins
